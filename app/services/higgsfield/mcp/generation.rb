require "net/http"

module Higgsfield
  module Mcp
    # Backend that drives the Higgsfield MCP server's tools directly:
    # media_upload → PUT → media_confirm → generate_*_batch → jobs_wait.
    # Uses the plan's credits and the same models as the Higgsfield app
    # (Nano Banana 2.1 for catalog photos, Kling 4.0 for videos).
    class Generation
      # Marks records whose hf_request_id is an MCP job id (usable as a reference).
      STATUS_MARKER = "mcp".freeze
      DONE = %w[completed].freeze
      FAILED = %w[failed nsfw ip_detected canceled].freeze

      def initialize(session: Session.new, config: Session.config)
        @session = session
        @config = config
      end

      def ready?
        @session.connected?
      end

      def submit_photo(photo)
        media_id = upload(Results.jpeg_bytes(photo), filename: "photo-#{photo.id}.jpg", content_type: "image/jpeg")
        params = @config[:image][:params].to_h.merge(
          model: @config[:image][:model],
          prompt: Prompts.catalog(photo.side, instructions: photo.instructions),
          medias: [ { value: media_id, role: "image_references" } ]
        )
        job_id = submit("generate_image_batch", params)
        photo.start_processing!(request_id: job_id, status_url: STATUS_MARKER)
      end

      def submit_video(video)
        references = video.garments.flat_map { |garment| garment.photos.select(&:completed?) }.map do |photo|
          { value: reference_for(photo), role: "image_references" }
        end
        prompt = Prompts.ugc_video(garment_names: video.garments.map(&:display_name), instructions: video.instructions)
        params = @config[:video][:params].to_h.merge(
          model: @config[:video][:model],
          prompt: prompt,
          duration: video.duration,
          medias: references
        )
        job_id = submit("generate_video_batch", params)
        video.update!(prompt: prompt)
        video.start_processing!(request_id: job_id, status_url: STATUS_MARKER)
      end

      # Checks one job. Returns :done or :pending.
      def poll(record)
        result = @session.call("jobs_wait", jobs: [ { index: 0, job_id: record.hf_request_id } ], timeout_seconds: 0)
        job = Array(result.is_a?(Hash) ? result["jobs"] : nil).first || {}
        status = job["status"].to_s

        if DONE.include?(status)
          Results.attach(record, job["result_url"])
          :done
        elsif FAILED.include?(status) || job["error"].present? && status.blank?
          record.fail!(Results.failure_message(status, job["error"]))
          :done
        else
          record.increment!(:poll_attempts)
          :pending
        end
      end

      private

      # A catalog photo made through MCP can be referenced by its job id;
      # otherwise (e.g. generated by the REST backend) upload the file.
      def reference_for(photo)
        return photo.hf_request_id if photo.hf_status_url == STATUS_MARKER && photo.hf_request_id.present?

        photo.catalog.open do |file|
          upload(file.read, filename: photo.catalog.filename.to_s, content_type: photo.catalog.content_type)
        end
      end

      def submit(tool, params)
        result = @session.call(tool, requests: [ { index: 0, params: params.merge(use_unlim: false) } ])
        job = Array(result.is_a?(Hash) ? result["jobs"] : nil).first
        return job.fetch("job_id") if job&.dig("job_id").present?

        detail = result.is_a?(Hash) ? (result["errors"] || result["failed"] || result).to_json : result.to_s
        raise RequestError, "A Higgsfield não aceitou a geração: #{detail.truncate(300)}"
      end

      # media_upload returns a presigned PUT URL; the bytes go straight to storage.
      def upload(bytes, filename:, content_type:)
        result = @session.call("media_upload", files: [ { filename: filename, content_type: content_type } ])
        target = Array(result.is_a?(Hash) ? result["uploads"] : nil).first
        raise RequestError, "A Higgsfield não devolveu URL de upload" unless target&.dig("upload_url")

        put(target["upload_url"], bytes, target["content_type"] || content_type)
        @session.call("media_confirm", media_ids: [ target["media_id"] ], type: "image")
        target["media_id"]
      end

      def put(url, bytes, content_type)
        uri = URI(url)
        request = Net::HTTP::Put.new(uri)
        request["Content-Type"] = content_type
        request["If-None-Match"] = "*" # part of the presigned signature
        request.body = bytes
        response = Net::HTTP.start(uri.host, uri.port, use_ssl: true, open_timeout: 10, read_timeout: 120) { it.request(request) }
        return if response.is_a?(Net::HTTPSuccess)

        error = response.code.to_i >= 500 ? TransientError : RequestError
        raise error, "Falha ao enviar a foto para a Higgsfield (#{response.code})"
      rescue Timeout::Error, SocketError, SystemCallError, OpenSSL::SSL::SSLError, IOError => e
        raise TransientError, "Falha de rede ao enviar a foto: #{e.message}"
      end
    end
  end
end
